#!/bin/sh
##########################################################################
#	Module	: check interface lines (UDP)
#	File	: chkudp.sh
##########################################################################

date +%Y/%m/%d-%H:%M:%S
cd $_P_BIN

if [ $# = 1 ] && [ $1 != "-h" ]; then
	px_chkudp_mp $1
elif [ $# = 2 ]; then
	px_chkudp_mp $1 $2
else
	echo "=========================================================="
	echo "[check interface lines (UDP)]"
	echo ""
	echo "Usage: chkudp.sh <sub name> <type>"
	echo "  e.g. 1) chkudp.sh pa"
	echo "       2) chkudp.sh pa ur"
	echo "=========================================================="
fi

##########################################################################
#	End of File (chkudp.sh)
##########################################################################

/*------------------------------------------------------------------------
#   Module  : convert string to long integer
#   File    : atolf.c
------------------------------------------------------------------------*/

/*------------------------------------------------------------------------
    Function Prototypes
------------------------------------------------------------------------*/
long    AtoLf(char *, int);

/*************************************************************************
    Function        : . convert string to long integer
    Parameters IN   : . p_ascii : string to convert
                      . p_len   : length of the string
    Parameters OUT  : .
    Return Code     : . long integer converted
*************************************************************************/
/*----------------------------------------------------------------------*/
long    AtoLf(char *p_ascii, int p_len)
/*----------------------------------------------------------------------*/
{
    int     i, u;
    long    jj;
    char    c;

    jj = u = 0;

    for (i = 0; i < p_len; i ++) {
        c = *(p_ascii+i);

        if (c >= '0' && c <= '9')
            jj = jj * 10 + (c - '0');
        else if (c == '-')
            u = 1;
    }

    if (u)
        jj = jj * -1;

    return (jj);
}   /* End of AtoLf ()  */


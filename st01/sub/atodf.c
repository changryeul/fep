/*------------------------------------------------------------------------
#   Module  : convert string to double
#   File    : atodf.c
------------------------------------------------------------------------*/

/*------------------------------------------------------------------------
    Function Prototypes
------------------------------------------------------------------------*/
double  AtoDf(char *, int);

/*************************************************************************
    Function        : . convert string to double
    Parameters IN   : . p_ascii : string to convert
                      . p_len   : length of the string
    Parameters OUT  : .
    Return Code     : . double converted
*************************************************************************/
/*----------------------------------------------------------------------*/
double  AtoDf(char *p_ascii, int p_len)
/*----------------------------------------------------------------------*/
{
    int     i, k, d, u;
    double  jj, js, ss;
    char    c;

    k = u = 0;
    js = ss = jj = 0.;

    for (i = 0; i < p_len; i ++) {
        c = *(p_ascii+i);

        if (c >= '0' && c <= '9') {
            if (k == 0)
                js = js * 10. + (c - '0');
            else {
                ss = ss * 10. + (c - '0');
                k ++;
            }
        }
        else {
            if (c == '.')
                k = 1;

            if (c == '-')
                u = 1;
        }
    }

    if (k > 0)
        k --;

    d = 1;
    for (i = 0; i < k; i++)
        d = d * 10;

    jj = js + ss/d;

    if (u)
        jj = jj * -1;

    return (jj);
}   /* End of AtoDf ()  */


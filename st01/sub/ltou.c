/*------------------------------------------------------------------------
#   Module  : convert lowercase to uppercase
#   File    : ltou.c
------------------------------------------------------------------------*/

/*------------------------------------------------------------------------
    Header Files
------------------------------------------------------------------------*/
#include    "fep_sub.h"

/*------------------------------------------------------------------------
    Function Prototypes
------------------------------------------------------------------------*/
char    *LtoU(char *, int);

/*************************************************************************
    Function        : . convert lowercase to uppercase
    Parameters IN   : . p_ltoubuf   : string to convert
                      . p_len       : data length
    Parameters OUT  : . p_ltoubuf   : string converted
    Return Code     : . char * (string converted)
*************************************************************************/
/*----------------------------------------------------------------------*/
char    *LtoU(char *p_ltoubuf, int p_len)
/*----------------------------------------------------------------------*/
{
    int     i;

    for (i = 0; i < p_len; i ++)
        *(p_ltoubuf+i) = (char)toupper (*(unsigned char *)(p_ltoubuf+i));

    return (p_ltoubuf);
}   /* End of LtoU ()   */


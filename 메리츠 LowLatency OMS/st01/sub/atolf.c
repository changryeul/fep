/*------------------------------------------------------------------------
	Function Prototypes
------------------------------------------------------------------------*/
long	AtoLf (char *, int);

/*************************************************************************
	Function		: . convert string to long integer
	Parameters IN	: . p_ascii	: string to convert
					  . p_len	: length of the string
	Parameters OUT	: .
	Return Code		: . long integer converted
*************************************************************************/
/*----------------------------------------------------------------------*/
long	AtoLf (char *p_ascii, int p_len)
/*----------------------------------------------------------------------*/
{
	int		i, j;
	long	jj;

	j = jj = 0;

	for (i = 0; i < p_len; i ++)
	{
		for (j = 0; j < 10; j ++)
		{
			if (*(p_ascii+i) == ('0' + j))
				break;
		}

		if (j >= 10)
			break;

		jj = jj * 10. + j;
	}

	return (jj);
}	/* End of AtoLf ()	*/


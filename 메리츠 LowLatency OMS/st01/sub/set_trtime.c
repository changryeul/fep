/*------------------------------------------------------------------------
#	Module	: set first and last transaction time
#	File	: set_trtime.c
------------------------------------------------------------------------*/

/*------------------------------------------------------------------------
	Header Files
------------------------------------------------------------------------*/
#include	"fep_sub.h"

/*------------------------------------------------------------------------
	Global Variables
------------------------------------------------------------------------*/
static short	set_flag = 1;

/*------------------------------------------------------------------------
	Function Prototypes
------------------------------------------------------------------------*/
void	Set_TR_Time (void);

/*************************************************************************
	Function		: . set first and last transaction time
	Parameters IN	: . void
	Parameters OUT	: .
	Return Code		: . void
*************************************************************************/
/*----------------------------------------------------------------------*/
void	Set_TR_Time (void)
/*----------------------------------------------------------------------*/
{
	char			tr_tm[8];
	struct timeval	tv;
	struct tm		*date, date1;

	gettimeofday (&tv, NULL);
	date = (struct tm *)localtime_r (&(tv.tv_sec), &date1);

	strftime (tr_tm, 7, "%H%M%S", date);
	if (set_flag) 
	{
		memcpy (PROC(D_K,P_K).tr_s_tm, tr_tm, 6);	
		set_flag = 0;
	}
	memcpy (PROC(D_K,P_K).tr_e_tm, tr_tm, 6);	

	return;
}	/* End of Set_TR_Time ()	*/

/*************************************************************************
	End of Program (set_trtime.c)
*************************************************************************/
